const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
function setup(initial=[]){
  let bank=structuredClone(initial),writes=0,calls=0,messages=[];
  const ctx={console,Date};vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(__dirname+'/Code.template.gs','utf8'),ctx);
  ctx.githubGet=()=>({content:structuredClone(bank),sha:'expected-sha'});
  ctx.githubPut=(path,value,sha)=>{assert.equal(sha,'expected-sha');bank=structuredClone(value);writes++;};
  ctx.tgSend=text=>messages.push(text);
  ctx.openAITaipeiAnswerBatch=()=>{calls++;return [{idx:0,val:'0'}];};
  return {ctx,bank:()=>bank,writes:()=>writes,calls:()=>calls,messages};
}
const question={course_id:'5609',q_text:'題目？',opt0:'甲',opt1:'乙',opt2:'丙',opt3:''};
const existing={...question,q_key:'題目？',val:'0'};
let s=setup([existing]);
assert.notEqual(s.ctx.taipeiOptionKey('1.5%'),s.ctx.taipeiOptionKey('15%'));
assert.notEqual(s.ctx.taipeiOptionKey('-5'),s.ctx.taipeiOptionKey('5'));
s.ctx.handleTaipeiQuizMissing({missing:[question]});
assert.equal(s.calls(),0,'known questions without rejection evidence do not cause paid retries');
assert.equal(s.messages.length,0);
const shuffled={...question,opt0:'乙',opt1:'甲',rejected_answers:['甲']};
let result=s.ctx.handleTaipeiQuizMissing({missing:[shuffled,shuffled],course:'測試課程'});
assert.equal(result.updated,1);assert.equal(result.added,0);assert.equal(s.calls(),1);
assert.equal(s.bank().length,1);assert.equal(s.bank()[0].opt0,'乙');assert.equal(s.bank()[0].val,'0');
assert.equal(s.bank()[0].verification_status,'ai_candidate');
assert.match(s.messages[0],/重新補答：1 題/);
s.ctx.handleTaipeiQuizMissing({missing:[shuffled]});
assert.equal(s.calls(),1,'repeated same rejection must not repeat API calls or notifications');
assert.equal(s.messages.length,1);
s=setup([existing]);
s.ctx.openAITaipeiAnswerBatch=()=>[{idx:0,val:'1'}];
result=s.ctx.handleTaipeiQuizMissing({missing:[shuffled]});
assert.equal(result.status,'error','AI cannot restore the explicitly rejected option');
assert.equal(s.writes(),0);
s=setup([existing]);
s.ctx.handleTaipeiQuizMissing({missing:[{...shuffled,opt2:'不同選項'}]});
assert.equal(s.calls(),0,'changed question versions cannot overwrite an existing entry');
s=setup([{...existing,verification_status:'platform_confirmed'}]);
result=s.ctx.handleTaipeiQuizSave({questions:[{...question,val:'1'}]});
assert.equal(result.skipped,1);assert.equal(s.writes(),0,'legacy unchecked fallback cannot overwrite confirmed answers');
result=s.ctx.handleTaipeiQuizSave({questions:[{...question,val:0,evidence:'platform_feedback'}]});
assert.equal(result.updated,1);assert.equal(s.bank()[0].val,'0');
assert.equal(s.bank()[0].verification_status,'platform_confirmed');
s=setup();
s.ctx.handleTaipeiQuizSave({questions:[{...question,val:'3',evidence:'platform_feedback'}]});
assert.equal(s.writes(),0,'an empty option is never saved as correct');
let prompt='';
// Exercise the original prompt builder separately from the response stub.
const raw={console};vm.createContext(raw);vm.runInContext(fs.readFileSync(__dirname+'/Code.template.gs','utf8'),raw);
raw.callOpenAI=messages=>{prompt=messages[1].content;return '[{"idx":0,"val":"0"}]';};
raw.openAITaipeiAnswerBatch([shuffled]);
assert.match(prompt,/0\. 乙/);assert.doesNotMatch(prompt,/1\. 甲/);
const multi={...question,type:'multiselect',q_text:'複選問題',opt3:'丁'};
s=setup();
for(const val of ['[]','["0","0"]','["4"]','0','[null]']) {
  s.ctx.handleTaipeiQuizSave({questions:[{...multi,val,evidence:'platform_feedback'}]});
}
assert.equal(s.writes(),0,'malformed checkbox sets are never saved');
s.ctx.handleTaipeiQuizSave({questions:[{...multi,val:[0,2],evidence:'platform_feedback'}]});
assert.equal(s.bank()[0].val,'["0","2"]');
assert.equal(s.bank()[0].type,'multiselect');
assert.equal(s.bank()[0].verification_status,'platform_confirmed');
const multiShuffled={...multi,opt0:'丙',opt1:'甲',opt2:'乙',rejected_combinations:[['甲','丙']]};
s.ctx.openAITaipeiAnswerBatch=()=>[{idx:0,values:['1','2']}];
result=s.ctx.handleTaipeiQuizMissing({missing:[multiShuffled]});
assert.equal(result.updated,1,'a rejected set is rechecked even after option shuffle');
assert.equal(s.bank()[0].val,'["1","2"]');
assert.equal(s.bank()[0].verification_status,'ai_candidate');
const writes=s.writes();
s.ctx.handleTaipeiQuizMissing({missing:[multiShuffled]});
assert.equal(s.writes(),writes,'new candidate is not repeatedly rewritten for an older rejected set');
s=setup();s.ctx.openAITaipeiAnswerBatch=()=>[{idx:0,values:['0','1']}];
result=s.ctx.handleTaipeiQuizMissing({missing:[{...multi,rejected_combinations:[['甲','乙']]}]});
assert.equal(result.status,'error');assert.equal(s.writes(),0,'a proven bad whole combination is rejected');
console.log('PASS: Taipei single/multiselect correction, shuffled options, deduplication, invalid AI answers and legacy overwrite protection.');
